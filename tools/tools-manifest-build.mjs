// Generates public/js/tools-manifest.js: the id, name and category of every mini-tool plus
// TOOL_CATS, and nothing else. The console shell (auth.js, console-nav.js) needs only this to
// count tools and build the Services menu, so it must not pull in the ~780 KB of tool code in
// js/tools/*; that loads on demand when the Toolbox opens (mini-tools.js).
//
//   node tools/tools-manifest-build.mjs
//
// Re-run after adding or renaming a tool. test/core/tools-manifest.test.mjs fails if the
// manifest drifts from the registry.
import { readdirSync, readFileSync, writeFileSync, mkdtempSync, mkdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const jsDir = join(root, "public", "js");

// Import the browser registry in Node by rewriting its absolute "/js/..." specifiers.
export async function loadRegistry() {
  const dir = mkdtempSync(join(tmpdir(), "dn-tools-"));
  mkdirSync(join(dir, "tools"));
  const fix = (s) => s.replace(/"\/js\/tools\//g, '"./tools/').replace(/"\/js\//g, '"./').replace(/\?v=[a-z0-9]+"/g, '"');
  writeFileSync(join(dir, "tools-registry.js"), fix(readFileSync(join(jsDir, "tools-registry.js"), "utf8")));
  for (const f of readdirSync(join(jsDir, "tools"))) {
    if (f.endsWith(".js")) writeFileSync(join(dir, "tools", f), fix(readFileSync(join(jsDir, "tools", f), "utf8")));
  }
  try {
    const m = await import(pathToFileURL(join(dir, "tools-registry.js")).href);
    return { TOOLS: m.TOOLS, TOOL_CATS: m.TOOL_CATS };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

export function manifestSource({ TOOLS, TOOL_CATS }) {
  const meta = TOOLS.map((t) => [t.id, t.name, t.cat]);
  return [
    "// GENERATED by tools/tools-manifest-build.mjs. Do not edit; edit js/tools/* and re-run.",
    "// Ids, names and categories of every mini-tool, for the console shell. The tool code itself",
    "// stays in js/tools/* and loads only when the Toolbox opens.",
    `export const TOOL_CATS = ${JSON.stringify(TOOL_CATS, null, 2)};`,
    `const M = ${JSON.stringify(meta)};`,
    "export const TOOL_META = M.map(([id, name, cat]) => ({ id, name, cat }));",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const reg = await loadRegistry();
  const out = join(jsDir, "tools-manifest.js");
  writeFileSync(out, manifestSource(reg));
  console.log(`wrote ${out}: ${reg.TOOLS.length} tools, ${Object.keys(reg.TOOL_CATS).length} categories`);
}
