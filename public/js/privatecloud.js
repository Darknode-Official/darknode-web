function rnd(n) { const a = crypto.getRandomValues(new Uint8Array(n)); return [...a].map((x) => "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789"[x % 55]).join(""); }

// Minimal YAML emitter for the compose object (handles our nested shapes).
function toYaml(obj, indent) {
  indent = indent || 0; const pad = "  ".repeat(indent); let out = "";
  for (const [k, v] of Object.entries(obj)) {
    if (Array.isArray(v)) {
      out += `${pad}${k}:\n` + v.map((it) => `${pad}  - ${yamlScalar(it)}`).join("\n") + "\n";
    } else if (v && typeof v === "object") {
      out += `${pad}${k}:\n` + toYaml(v, indent + 1);
    } else {
      out += `${pad}${k}: ${yamlScalar(v)}\n`;
    }
  }
  return out;
}
function yamlScalar(v) { const s = String(v); return /[:#{}\[\],&*?|<>=!%@`"']/.test(s) || s === "" ? JSON.stringify(s) : s; }

function build(ctx, chosen) {
  const services = {}, env = {};
  const useTraefik = chosen.includes("traefik");
  for (const id of chosen) {
    const svc = SERVICES[id]; if (!svc) continue;
    const c = svc.compose(ctx);
    if (useTraefik && id !== "traefik") {
      const host = id + "." + ctx.domain;
      c.labels = ["traefik.enable=true", `traefik.http.routers.${id}.rule=Host(\`${host}\`)`, `traefik.http.routers.${id}.entrypoints=websecure`];
    }
    services[id] = c;
    if (svc.env) Object.assign(env, svc.env(ctx));
  }
  const compose = "# Generated by Sentinel — Private Cloud Generator\n" + toYaml({ services });
  const envText = Object.entries(env).map(([k, v]) => `${k}=${v}`).join("\n") || "# no secrets required for the selected services";
  const readme = "# My private cloud\n\nGenerated by Sentinel. Run everything with:\n\n```\ndocker compose up -d\n```\n\n## Services\n\n" +
    chosen.map((id) => `- **${SERVICES[id].name}** — ${SERVICES[id].desc} → ${SERVICES[id].url(ctx)}`).join("\n") +
    "\n\n## Notes\n- Data is stored under `" + ctx.data + "`.\n- Secrets are in `.env` — keep it private.\n" +
    (useTraefik ? "- Traefik routes each service at `<name>." + ctx.domain + "` over HTTPS. Point your DNS/hosts file at this machine.\n" : "- Each service is published on its own localhost port (see above).\n") +
    "\n> Use only on infrastructure you own.\n";
  return { compose, envText, readme };
}

function download(name, text) {
  const url = URL.createObjectURL(new Blob([text], { type: "text/plain" }));
  const a = document.createElement("a"); a.href = url; a.download = name; document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

