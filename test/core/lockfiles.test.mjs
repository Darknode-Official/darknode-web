const parse = (fmt) => LOCKFILE_PARSERS[fmt](SAMPLES[fmt].text);
const by = (deps, name) => deps.find((d) => d.name === name);

group("lockfiles: one parser per format", () => {
  test("every format has a parser and a sample, and file names map to it", () => {
    assert.deepEqual(Object.keys(LOCKFILE_PARSERS).sort(), Object.keys(SAMPLES).sort());
    for (const [fmt, s] of Object.entries(SAMPLES)) assert.equal(formatForName("repo/sub/" + s.file), fmt, s.file);
    assert.equal(formatForName("requirements-dev.txt"), "requirements");
    assert.equal(formatForName("README.md"), null);
  });
  test("content detection routes every sample without its file name", () => {
    for (const [fmt, s] of Object.entries(SAMPLES)) assert.equal(detectFormat(s.text), fmt, fmt);
    assert.equal(detectFormat("  \n "), null);
  });
  test("floorVersion: exact pins, including =, v and pre-release forms; ranges give the lower bound", () => {
    assert.deepEqual(floorVersion("4.17.21"), { version: "4.17.21", exact: true });
    assert.deepEqual(floorVersion("=2.3.3"), { version: "2.3.3", exact: true });
    assert.deepEqual(floorVersion("v1.2.3-rc.1"), { version: "1.2.3-rc.1", exact: true });
    assert.deepEqual(floorVersion("^4.18.2"), { version: "4.18.2", exact: false });
    assert.deepEqual(floorVersion(">=1.0 <2"), { version: "1.0", exact: false });
  });
  test("floorVersion: an upper bound, exclusion, tag or source has no version to scan at; x-ranges floor to .0", () => {
    for (const s of ["<2.0.0", "<=2", "!=1.4", "< 3", "*", "latest", "github:user/repo", "file:../lib", "npm:other@^1.2.0", ""]) assert.deepEqual(floorVersion(s), { version: "", exact: false }, s);
    assert.deepEqual(floorVersion("1.x"), { version: "1.0.0", exact: false });
    assert.deepEqual(floorVersion("~2.3.x"), { version: "2.3.0", exact: false });
    assert.deepEqual(floorVersion("~> 1.2"), { version: "1.2", exact: false });
    const r = parseLockfile("requirements", "requests<2.0\nflask!=2.1\ndjango>=4.2,<5\n");
    assert.deepEqual(r.map((d) => [d.name, d.version]), [["requests", ""], ["flask", ""], ["django", "4.2"]]);
  });
  test("package.json: direct, ranges flagged, optional/dev types, declaring lines", () => {
    const d = parse("npm-manifest");
    assert.deepEqual(d.map((x) => [x.name, x.version, x.exact, x.type, x.line]), [
      ["express", "4.18.2", false, "production", 4], ["lodash", "4.17.21", true, "production", 5], ["fsevents", "2.3.3", true, "production", 8], ["jest", "29.7.0", true, "development", 11],
    ]);
    assert.ok(d.every((x) => x.direct === true && x.ecosystem === "npm"));
  });
  test("package-lock.json: direct vs transitive, aliases under the real name, links skipped", () => {
    const d = parse("package-lock");
    assert.deepEqual(d.map((x) => [x.name, x.version, x.direct]), [["express", "4.18.2", true], ["accepts", "1.3.8", false], ["strip-ansi", "6.0.1", true]]);
    assert.equal(by(d, "express").line, SAMPLES["package-lock"].text.split("\n").findIndex((l) => l.includes('"node_modules/express"')) + 1);
  });
  test("yarn.lock: scoped names, merged specifiers, header line", () => {
    const d = parse("yarn-lock");
    assert.deepEqual(d.map((x) => [x.name, x.version, x.line]), [["@babel/core", "7.23.2", 4], ["lodash", "4.17.21", 8]]);
    assert.equal(parseLockfile("yarn-lock", '__metadata:\n  version: 6\n\n"app@workspace:.":\n  version: 0.0.0-use.local\n\n"lodash@npm:^4.17.21":\n  version: 4.17.21\n').map((x) => x.name).join(), "lodash", "the workspace itself is not a dependency");
  });
  test("pnpm-lock.yaml v9: importers give direct + dev, snapshots give edges", () => {
    const d = parse("pnpm-lock");
    assert.deepEqual(d.map((x) => [x.name, x.version, x.direct, x.type]), [["accepts", "1.3.8", false, "production"], ["express", "4.18.2", true, "production"], ["vitest", "1.0.4", true, "development"]]);
    assert.deepEqual(by(d, "express").requires, ["accepts@1.3.8"]);
    const v6 = parseLockfile("pnpm-lock", "lockfileVersion: '6.0'\n\ndependencies:\n  ms:\n    specifier: ^2.1.3\n    version: 2.1.3\n\npackages:\n\n  /ms@2.1.3:\n    resolution: {integrity: sha512-x}\n    dev: false\n");
    assert.deepEqual(v6.map((x) => [x.name, x.version, x.direct]), [["ms", "2.1.3", true]]);
  });
  test("requirements.txt: == and === are exact, extras and comments are handled, -e lines skipped", () => {
    const d = parse("requirements");
    assert.deepEqual(d.map((x) => [x.name, x.version, x.exact, x.line]), [["django", "4.2.7", true, 2], ["requests", "2.31.0", false, 3], ["uvicorn", "0.24.0", true, 4], ["numpy", "1.26.2", true, 6]]);
  });
  test("poetry.lock: lower-cased names, dev category, header lines, subtables ignored", () => {
    const d = parse("poetry-lock");
    assert.deepEqual(d.map((x) => [x.name, x.version, x.type, x.line]), [["certifi", "2023.11.17", "production", 3], ["pytest", "7.4.3", "development", 9]]);
  });
  test("Pipfile.lock: default and develop, git entries without a version skipped", () => {
    const d = parse("pipfile-lock");
    assert.deepEqual(d.map((x) => [x.name, x.version, x.type, x.ecosystem]), [["flask", "3.0.0", "production", "pypi"], ["pytest", "7.4.3", "development", "pypi"]]);
    assert.ok(d[0].line > 1);
  });
  test("go.mod: single and block requires, // indirect, +incompatible dropped", () => {
    const d = parse("go-mod");
    assert.deepEqual(d.map((x) => [x.name, x.version, x.direct, x.line]), [["github.com/spf13/cobra", "1.8.0", true, 5], ["github.com/gin-gonic/gin", "1.9.1", true, 8], ["github.com/docker/docker", "24.0.7", false, 9]]);
  });
  test("go.sum: one entry per module@version", () => {
    assert.deepEqual(parse("go-sum").map((x) => [x.name, x.version, x.line]), [["github.com/gin-gonic/gin", "1.9.1", 1], ["golang.org/x/net", "0.17.0", 3]]);
  });
  test("Cargo.lock: registry crates with edges; the workspace crate is local and left out of parseLockfile", () => {
    const all = parse("cargo-lock");
    assert.deepEqual(all.map((x) => [x.name, !!x.local, x.direct]), [["app", true, false], ["serde", false, true], ["serde_derive", false, false]]);
    assert.deepEqual(by(all, "serde").requires, ["serde_derive@1.0.193"]);
    assert.deepEqual(parseLockfile("cargo-lock", SAMPLES["cargo-lock"].text).map((x) => x.name), ["serde", "serde_derive"]);
  });
  test("Gemfile and Gemfile.lock: platform suffix dropped, DEPENDENCIES are direct", () => {
    assert.deepEqual(parse("gemfile").map((x) => [x.name, x.version, x.exact]), [["rails", "7.1.2", true], ["puma", "6.0", false]]);
    const d = parse("gemfile-lock");
    assert.deepEqual(d.map((x) => [x.name, x.version, x.direct, x.line]), [["nokogiri", "1.15.5", true, 4], ["racc", "1.7.3", false, 6]]);
  });
  test("composer.lock: packages and packages-dev with licenses, v prefix dropped", () => {
    const d = parse("composer-lock");
    assert.deepEqual(d.map((x) => [x.name, x.version, x.type, x.license.join()]), [["monolog/monolog", "3.5.0", "production", "MIT"], ["dev/branch", "dev-main", "production", ""], ["phpunit/phpunit", "10.5.2", "development", "BSD-3-Clause"]]);
  });
  test("pom.xml and gradle.lockfile: Maven coordinates with lines; test-only configurations are development", () => {
    assert.deepEqual(parse("pom").map((x) => [x.name, x.version, x.line]), [["org.apache.logging.log4j:log4j-core", "2.14.1", 3]]);
    assert.deepEqual(parse("gradle-lockfile").map((x) => [x.name, x.version, x.type, x.line]), [["com.google.guava:guava", "32.1.3-jre", "production", 4], ["junit:junit", "4.13.2", "development", 5]]);
  });
  test("malformed input gives null, never a throw", () => {
    for (const fmt of Object.keys(LOCKFILE_PARSERS)) assert.equal(LOCKFILE_PARSERS[fmt]("{ not valid"), null, fmt);
  });
});

group("lockfiles: the three consumers", () => {
  test("Supply Chain reads all 15 formats from pasted text, with OSV names for every ecosystem", () => {
    assert.equal(SCA_OSV, OSV_ECOSYSTEM);
    for (const [fmt, s] of Object.entries(SAMPLES)) {
      const d = autoDetectAndParse(s.text);
      assert.ok(d && d.length, fmt + " parsed");
      for (const x of d) assert.ok(OSV_ECOSYSTEM[x.ecosystem], fmt + ": " + x.ecosystem + " has an OSV name");
    }
    assert.deepEqual(autoDetectAndParse(SAMPLES["cargo-lock"].text).map((x) => x.ecosystem), ["cargo", "cargo"], "Cargo.lock is no longer read as poetry.lock");
  });
  test("Code Scanner keeps exact pins only and names ecosystems the OSV way", () => {
    const m = (fmt) => parseManifest(SAMPLES[fmt].file, SAMPLES[fmt].text);
    assert.deepEqual(m("npm-manifest").map((x) => x.name), ["lodash", "fsevents", "jest"]);
    assert.deepEqual(m("composer-lock").map((x) => [x.name, x.version, x.ecosystem]), [["monolog/monolog", "3.5.0", "Packagist"], ["phpunit/phpunit", "10.5.2", "Packagist"]]);
    assert.deepEqual(m("cargo-lock").map((x) => x.ecosystem), ["crates.io", "crates.io"]);
    assert.deepEqual(m("gradle-lockfile").map((x) => [x.name, x.ecosystem, x.line]), [["com.google.guava:guava", "Maven", 4], ["junit:junit", "Maven", 5]]);
    assert.deepEqual(m("pnpm-lock").map((x) => x.name), ["accepts", "express", "vitest"]);
    assert.deepEqual(parseManifest("go.sum", SAMPLES["go-sum"].text), [], "go.sum is not one of the Code Scanner's manifests");
  });
  test("License Audit builds components, licenses and paths from the shared parsers", () => {
    const one = (fmt) => parseInput({ name: SAMPLES[fmt].file, text: SAMPLES[fmt].text }).files[0];
    const comp = one("composer-lock").components;
    assert.deepEqual(comp.map((c) => [c.name, c.declared, c.dev]), [["monolog/monolog", "MIT", false], ["dev/branch", "", false], ["phpunit/phpunit", "BSD-3-Clause", true]]);
    const cargo = one("cargo-lock");
    assert.equal(cargo.project.name, "app");
    assert.deepEqual(cargo.components.map((c) => [c.name, c.path && c.path.join(">"), c.direct]), [["serde", "app>serde", true], ["serde_derive", "app>serde>serde_derive", false]]);
    const pnpm = one("pnpm-lock");
    assert.deepEqual(pnpm.components.map((c) => [c.name, c.path && c.path.join(">"), c.dev]), [["accepts", "(project)>express>accepts", false], ["express", "(project)>express", false], ["vitest", "(project)>vitest", true]]);
    assert.deepEqual(one("pipfile-lock").components.map((c) => [c.name, c.purl, c.dev]), [["flask", "pkg:pypi/flask@3.0.0", false], ["pytest", "pkg:pypi/pytest@7.4.3", true]]);
    const lock = one("package-lock").components;
    assert.ok(lock.some((c) => c.name === "strip-ansi" && c.purl === "pkg:npm/strip-ansi@6.0.1"), "an aliased install is the real package");
  });
});
