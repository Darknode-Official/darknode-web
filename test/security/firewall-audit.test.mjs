// ---------------------------------------------------------------- CIDR library
group("fwa: addresses", () => {
  test("parseIPv4 / fmt roundtrip and bounds", () => {
    assert.equal(fmtRange(parseRange("192.168.1.10")), "192.168.1.10");
    assert.equal(parseIPv4("256.1.1.1"), null);
    assert.equal(parseIPv4("1.2.3"), null);
  });
  test("parseIPv6 handles ::, embedded v4, and /n", () => {
    assert.ok(parseIPv6("::1") === 1n);
    assert.ok(parseIPv6("2001:db8::1") !== null);
    assert.ok(parseIPv6("::ffff:192.0.2.1") !== null);
    assert.equal(parseIPv6("2001:db8:::1"), null);
    assert.equal(fmtRange(parseRange("2001:db8::/32")), "2001:db8::/32");
    assert.equal(fmtRange(parseRange("::/0")), "::/0");
  });
  test("CIDR, dotted mask, wildcard and range forms", () => {
    assert.equal(fmtRange(parseRange("10.0.0.0/8")), "10.0.0.0/8");
    assert.equal(fmtRange(parseRange("10.1.2.3/255.255.255.0")), "10.1.2.0/24");
    assert.equal(fmtRange(parseRange("10.1.2.3 255.255.255.0")), "10.1.2.0/24");
    assert.equal(fmtRange(rangeFromWildcard("192.168.10.0", "0.0.0.255")), "192.168.10.0/24");
    assert.equal(rangeFromWildcard("10.0.0.0", "0.255.0.255"), null, "non-contiguous wildcard is not one range");
    assert.equal(fmtRange(parseRange("10.0.0.1-10.0.0.9")), "10.0.0.1-10.0.0.9");
    assert.ok(isNetmask("255.255.254.0") && !isNetmask("255.0.255.0"));
    assert.ok(isWildcard("0.0.0.255") && !isWildcard("255.0.0.255"));
  });
  test("0.0.0.0/0 and 'any' are the full v4 space; /32 is a host", () => {
    assert.deepEqual(parseRange("0.0.0.0/0"), V4_ALL);
    assert.deepEqual(parseRange("any"), V4_ALL);
    const h = parseRange("203.0.113.7/32");
    assert.ok(h.lo === h.hi);
    assert.ok(rangeContains(V4_ALL, h) && !rangeContains(h, V4_ALL));
    assert.notOk(rangeContains(V4_ALL, V6_ALL), "families never contain each other");
  });
  test("containment and overlap", () => {
    const a = parseRange("10.0.0.0/8"), b = parseRange("10.1.0.0/16"), c = parseRange("10.1.255.0/24"), d = parseRange("11.0.0.0/8");
    assert.ok(rangeContains(a, b) && rangeContains(b, c) && rangeContains(a, c));
    assert.notOk(rangeContains(b, a));
    assert.ok(rangeOverlaps(a, b) && !rangeOverlaps(a, d));
    const e = parseRange("10.0.0.0-10.1.0.5"), f = parseRange("10.1.0.0/24");
    assert.ok(rangeOverlaps(e, f) && !rangeContains(e, f) && !rangeContains(f, e), "partial overlap is neither containment");
  });
  test("mergeRanges joins adjacent halves so a union can contain a whole", () => {
    const halves = [parseRange("10.0.0.128/25"), parseRange("10.0.0.0/25")];
    const m = mergeRanges(halves);
    assert.equal(m.length, 1);
    assert.ok(rangesCover(halves, parseRange("10.0.0.0/24")));
    assert.notOk(rangesCover([parseRange("10.0.0.0/25"), parseRange("10.0.1.0/25")], parseRange("10.0.0.0/24")));
  });
  test("addrContains with any / symbols / unresolved", () => {
    const any = addrSet({ any: true }), net = addrSet({ ranges: [parseRange("10.0.0.0/8")] }), host = addrSet({ ranges: [parseRange("10.9.9.9")] });
    assert.ok(addrContains(any, net) && addrContains(net, host) && !addrContains(host, net) && !addrContains(net, any));
    assert.ok(isAnyAddr(addrSet({ ranges: [V4_ALL] })), "explicit 0.0.0.0/0 is any");
    const sym = addrSet({ symbols: ["LAN net"] });
    assert.ok(addrContains(any, sym) && addrContains(sym, addrSet({ symbols: ["lan net"] })) && !addrContains(net, sym));
    const unres = addrSet({ unresolved: ["GRP"] });
    assert.notOk(addrContains(any, unres), "unresolved is never contained (conservative)");
    assert.notOk(addrContains(unres, host));
    const neg = addrSet({ ranges: [parseRange("10.0.0.0/8")], negated: true });
    assert.notOk(addrContains(neg, host) || addrContains(any, neg));
  });
  test("externalSize excludes internal space; DEFAULT_INTERNAL parses", () => {
    const { ranges, bad } = parseInternalList(DEFAULT_INTERNAL);
    assert.equal(bad.length, 0);
    assert.ok(externalSize(addrSet({ ranges: [parseRange("10.0.0.0/8")] }), ranges) === 0n);
    assert.ok(externalSize(addrSet({ ranges: [parseRange("8.0.0.0/8")] }), ranges) === (1n << 24n));
    assert.ok(externalSize(addrSet({ ranges: [parseRange("0.0.0.0/1")] }), ranges) < (1n << 31n));
  });
});

