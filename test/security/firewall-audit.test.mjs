// ---------------------------------------------------------------- shadowing
group("fwa: shadowing correctness", () => {
  const res = audit(FX.iptables);
  test("true shadow: deny after broader allow is high (bypass) and marked", () => {
    const shd = byType(res, "shadowed");
    assert.ok(shd.some((f) => f.severity === "high" && f.evidence.some((e) => e.idx === 8) && f.evidence.some((e) => e.idx === 3)), JSON.stringify(shd.map((f) => f.title)));
    assert.equal(rule(res, 8).shadowedBy, 3);
  });
  test("redundant: same action fully contained is low", () => {
    const red = byType(res, "redundant");
    assert.ok(red.some((f) => f.evidence.some((e) => e.idx === 5) && f.evidence.some((e) => e.idx === 4)));
    assert.equal(rule(res, 5).redundantOf, 4);
  });
  test("partial overlap is NOT flagged (different ports, different sources)", () => {
    // #9 allow 10/8:8080 and #10 deny 10/8:8081 overlap on source only -> no shadow
    assert.equal(rule(res, 10).shadowedBy, null);
    assert.notOk(rule(res, 10).flags.includes("shadowed"));
    // multiport 80,443 vs rdp 3389: unrelated
    assert.notOk(rule(res, 7).flags.includes("shadowed") || rule(res, 7).flags.includes("redundant"));
  });
  test("a wider later rule is not shadowed by a narrower earlier one", () => {
    const r = audit("*filter\n:INPUT DROP [0:0]\n-A INPUT -s 10.1.0.0/16 -p tcp --dport 22 -j ACCEPT\n-A INPUT -s 10.0.0.0/8 -p tcp --dport 22 -j ACCEPT\nCOMMIT\n");
    assert.equal(byType(r, "shadowed").length, 0); assert.equal(byType(r, "redundant").length, 0);
  });
  test("state/interface mismatch prevents a false shadow; different chains never shadow", () => {
    const r = audit("*filter\n:INPUT DROP [0:0]\n:FORWARD DROP [0:0]\n-A INPUT -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT\n-A INPUT -i eth1 -p tcp --dport 22 -j ACCEPT\n-A INPUT -p tcp --dport 22 -j DROP\n-A FORWARD -p tcp --dport 22 -j DROP\nCOMMIT\n");
    assert.equal(byType(r, "shadowed").length, 0, "eth1-only allow does not cover a drop for all interfaces");
    assert.equal(byType(r, "redundant").length, 0);
  });
  test("matchContains direct: proto any vs tcp, ports, src", () => {
    const a = parseIptables("-A INPUT -s 10.0.0.0/8 -j ACCEPT").rules[0];
    const b = parseIptables("-A INPUT -s 10.2.0.0/16 -p tcp --dport 22 -j ACCEPT").rules[0];
    assert.ok(matchContains(a, b)); assert.notOk(matchContains(b, a));
  });
  test("Windows: block-overrides-allow instead of first-match; order irrelevant", () => {
    const r = audit(FX.win);
    const shd = byType(r, "shadowed");
    assert.equal(shd.length, 1); assert.equal(shd[0].severity, "medium"); assert.ok(/overridden/.test(shd[0].title));
    assert.equal(byType(r, "exposure").length, 0, "RDP allow is dead, so not reported as exposed");
  });
});

